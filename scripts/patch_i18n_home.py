SEARCH = {
    "en": {"moreFilters": "Show price filter", "allSubcategories": "All subcategories"},
    "ru": {"moreFilters": "Показать фильтр цены", "allSubcategories": "Все подкатегории"},
    "tj": {"moreFilters": "Филтри нархро нишон диҳ", "allSubcategories": "Ҳама зеркатегорияҳо"},
}


def main():
    for lang in ("en", "ru", "tj"):
        path = os.path.join(LOCALES, f"{lang}.json")
        with io.open(path, encoding="utf-8") as f:
            data = json.load(f, object_pairs_hook=collections.OrderedDict)

        added = []
        for section, keys in (("home", HOME[lang]), ("search", SEARCH[lang])):
            target = data.setdefault(section, collections.OrderedDict())
            for k, v in keys.items():
                if k in target:
                    continue
                target[k] = v
                added.append(f"{section}.{k}")

        with io.open(path, "w", encoding="utf-8", newline="\n") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print("patched", path, "added:", added)


if __name__ == "__main__":
    main()
